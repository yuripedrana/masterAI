n_iniziale = 30
print("Il valore iniziale di n è:", n_iniziale)

n_iniziale_float = float(n_iniziale)
print("Il valore di n come float è:", n_iniziale_float)

n_iniziale_str = str(n_iniziale)
print("Il valore di n come stringa è:", n_iniziale_str)

n_iniziale_bool = bool(n_iniziale)
print("Il valore di n come booleano è:", n_iniziale_bool)

n_finale = n_iniziale * 3
print("inizio:", n_iniziale, "finale:", n_finale)